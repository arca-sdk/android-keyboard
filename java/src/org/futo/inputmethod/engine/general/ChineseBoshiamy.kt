/**
 * Boshiamy (嘸蝦米) input for [ChineseIME], used by layouts with imeHint "boshiamy".
 *
 * Boshiamy is a shape-based method: each character has a code of up to five keys, and typing a code
 * lists the characters it stands for. A code only matches exactly, and the candidates keep the
 * order of the table rather than being learned.
 *
 * The code table is proprietary and its licence doesn't allow redistributing it, so it isn't
 * bundled. Users import their own copy instead, in the format its vendor publishes for IBus (an
 * ibus-table SQLite database), which is converted to a RIME dictionary on the device. Until then
 * the schema has an empty dictionary, so nothing typed has candidates.
 */
object ChineseBoshiamy {
    const val SchemaId = "futo_boshiamy"

    private const val DictionaryFile = "$SchemaId.dict.yaml"

    // Besides the letters characters are typed with, these are used for punctuation, symbols and
    // kana. The layout types all of them as-is
    const val CodeKeys = "abcdefghijklmnopqrstuvwxyz,.'[]"
    private const val MaxCodeLength = 5

    // The four official tables are 0.5 to 1.3 MB
    private const val MaxImportSize = 32L * 1024L * 1024L

    private const val TableNamePrefix = "# table: "
    private const val TableEntriesPrefix = "# entries: "

    data class TableInfo(val name: String, val entries: Int)

    class InvalidTableException : Exception("Not an ibus-table database with Boshiamy codes")

    private val schema = """
        # Rime schema
        # encoding: utf-8
        #
        # Generated by FUTO Keyboard, any changes will be overwritten.

        schema:
          schema_id: $SchemaId
          name: 嘸蝦米
          version: "1"
          description: |
            Boshiamy input, using the code table imported by the user.

        switches:
          - name: ascii_mode
            reset: 0
            states: [ 中文, 西文 ]

        # No punctuator, as the punctuation keys are part of the codes. Other symbols are typed
        # as-is, as on desktop
        engine:
          processors:
            - ascii_composer
            - speller
            - selector
            - navigator
            - express_editor
          segmentors:
            - ascii_segmentor
            - abc_segmentor
            - fallback_segmentor
          translators:
            - table_translator
          filters:
            - simplifier
            - uniquifier

        speller:
          alphabet: "$CodeKeys"
          # Not the default, which includes the apostrophe
          delimiter: " "
          # A key typed after a full code selects its first character and starts the next code,
          # or drops the code if it has none
          max_code_length: $MaxCodeLength
          auto_clear: max_length

        translator:
          dictionary: $SchemaId
          enable_user_dict: false
          enable_sentence: false
          enable_encoder: false
          enable_completion: false

        __patch:
          - $SchemaId.custom:/patch?
    """.trimIndent() + "\n"

    private fun dictionaryHeader(info: TableInfo) = buildString {
        appendLine("# Rime dictionary")
        appendLine("# encoding: utf-8")
        appendLine("#")
        appendLine("# Converted by FUTO Keyboard from the table the user imported.")
        appendLine("$TableNamePrefix${info.name}")
        appendLine("$TableEntriesPrefix${info.entries}")
        appendLine()
        appendLine("---")
        appendLine("name: $SchemaId")
        appendLine("version: \"1\"")
        appendLine("sort: original")
        appendLine("columns:")
        appendLine("  - text")
        appendLine("  - code")
        appendLine("...")
        // Otherwise an entry for the character # would be read as a comment
        appendLine("# no comment")
    }

    // Lets the schema be deployed before a table is imported
    private val emptyDictionary = dictionaryHeader(TableInfo("none", 0))

    // Kept outside RIME's shared and user directories, which get emptied when the dictionary
    // download changes and when the learned words are cleared
    private fun tableFile(context: Context) =
        File(File(ChineseIME.getRimeDir(context), "boshiamy"), DictionaryFile)

    fun hasTable(context: Context) = tableFile(context).isFile

    /** The imported table, or null if there is none */
    fun tableInfo(context: Context): TableInfo? {
        val file = tableFile(context)
        if(!file.isFile) return null

        return try {
            val header = file.bufferedReader().useLines { lines -> lines.take(8).toList() }
            fun value(prefix: String) =
                header.firstOrNull { it.startsWith(prefix) }?.removePrefix(prefix)

            TableInfo(
                value(TableNamePrefix) ?: "?",
                value(TableEntriesPrefix)?.toIntOrNull() ?: 0
            )
        } catch(e: IOException) {
            null
        }
    }

    private fun isValidEntry(code: String?, text: String?) =
        code != null && text != null
                && code.length in 1..MaxCodeLength && code.all { it in CodeKeys }
                && text.isNotBlank() && text.none { it.isISOControl() }

    private fun readAttribute(db: SQLiteDatabase, attribute: String): String? = try {
        db.rawQuery("SELECT val FROM ime WHERE attr = ?", arrayOf(attribute)).use {
            if(it.moveToFirst()) it.getString(0) else null
        }
    } catch(e: SQLiteException) {
        null
    }

    private fun convertTable(database: File, destination: File): TableInfo {
        // Read only, and without the collators Android would otherwise set up by writing to it
        val flags = SQLiteDatabase.OPEN_READONLY or SQLiteDatabase.NO_LOCALIZED_COLLATORS
        return SQLiteDatabase.openDatabase(database.path, null, flags).use { db ->
            val name = listOfNotNull(
                readAttribute(db, "name.zh_tw") ?: readAttribute(db, "name"),
                readAttribute(db, "serial_number")
            ).joinToString(" ") { value ->
                value.filterNot { it.isISOControl() }.trim().take(64)
            }.ifBlank { "?" }

            // Candidates of a code are listed in the order they are in the dictionary
            val query = "SELECT tabkeys, phrase FROM phrases ORDER BY tabkeys, freq DESC, rowid"
            val entries = db.rawQuery(query, null).use { cursor ->
                buildList {
                    while(cursor.moveToNext()) {
                        val code = cursor.getString(0)
                        val text = cursor.getString(1)
                        if(isValidEntry(code, text)) add(text to code)
                    }
                }
            }

            if(entries.isEmpty()) throw InvalidTableException()

            val info = TableInfo(name, entries.size)
            destination.bufferedWriter().use { writer ->
                writer.write(dictionaryHeader(info))
                entries.forEach { (text, code) ->
                    writer.write(text)
                    writer.write("\t")
                    writer.write(code)
                    writer.write("\n")
                }
            }

            info
        }
    }

    /**
     * Converts the ibus-table database at [uri] and keeps it as the table to type with, replacing
     * the previous one. Reads and writes files, so it must not be called on the main thread.
     *
     * @throws InvalidTableException if the file isn't a table
     */
    @Throws(IOException::class, InvalidTableException::class)
    fun importTable(context: Context, uri: Uri): TableInfo {
        val table = tableFile(context)
        val directory = table.parentFile ?: throw IOException("No directory for the table")
        if(!directory.isDirectory && !directory.mkdirs()) {
            throw IOException("Failed to create the table directory")
        }

        // SQLite needs a file to open, and deletes the ones it finds to be corrupt
        val database = File.createTempFile("boshiamy", ".db", context.cacheDir)
        val converted = File(directory, "$DictionaryFile.tmp")
        try {
            val input = context.contentResolver.openInputStream(uri)
                ?: throw IOException("Failed to open the picked file")
            input.use {
                database.outputStream().use { output ->
                    val buffer = ByteArray(64 * 1024)
                    var total = 0L
                    while(true) {
                        val read = input.read(buffer)
                        if(read < 0) break

                        total += read
                        if(total > MaxImportSize) throw InvalidTableException()
                        output.write(buffer, 0, read)
                    }
                }
            }

            val info = try {
                convertTable(database, converted)
            } catch(e: SQLiteException) {
                // e.g. not a database, or one without the tables of ibus-table
                throw InvalidTableException()
            }

            if(!converted.renameTo(table)) throw IOException("Failed to store the table")
            return info
        } finally {
            database.delete()
            converted.delete()
        }
    }

    fun removeTable(context: Context) {
        tableFile(context).delete()
    }

    /**
     * Writes the schema and its dictionary to RIME's user directory, only touching files whose
     * content changed
     */
    fun writeSchemaFiles(context: Context, userDir: File) {
        if(!userDir.isDirectory) return

        val table = tableFile(context)
        val dictionary = if(table.isFile) table.readBytes() else emptyDictionary.toByteArray()

        listOf(
            File(userDir, "$SchemaId.schema.yaml") to schema.toByteArray(),
            File(userDir, DictionaryFile) to dictionary
        ).forEach { (file, content) -> ChineseGeneratedSchemas.writeIfChanged(file, content) }

        ChineseGeneratedSchemas.updateSchemaList(userDir)
    }
}

/** Imports, replaces and removes the table Boshiamy layouts type with */
@Composable
fun ChineseBoshiamyTableSetting() {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()

    var table by remember { mutableStateOf(ChineseBoshiamy.tableInfo(context)) }
    var importing by remember { mutableStateOf(false) }

    val picker = rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()) { uri ->
        uri ?: return@rememberLauncherForActivityResult

        importing = true
        scope.launch {
            // Not cancelled by leaving the screen, so that a stored table always gets loaded
            val result = withContext(Dispatchers.IO + NonCancellable) {
                runCatching { ChineseBoshiamy.importTable(context.applicationContext, uri) }
                    .onSuccess { GlobalIMEMessage.tryEmit(IMEMessage.ReloadResources) }
            }

            importing = false
            result.onSuccess { table = it }.onFailure {
                val message = when(it) {
                    is ChineseBoshiamy.InvalidTableException ->
                        R.string.chinese_setting_boshiamy_table_invalid
                    else -> R.string.chinese_setting_boshiamy_table_failed
                }
                Toast.makeText(context, message, Toast.LENGTH_LONG).show()
            }
        }
    }

    NavigationItem(
        title = stringResource(R.string.chinese_setting_boshiamy_table),
        style = NavigationItemStyle.MiscNoArrow,
        navigate = {
            // The tables have no file type of their own to filter by
            if(!importing) picker.launch(arrayOf("*/*"))
        },
        subtitle = when {
            importing -> stringResource(R.string.chinese_setting_boshiamy_table_importing)
            else -> table?.let {
                stringResource(R.string.chinese_setting_boshiamy_table_imported, it.name, it.entries)
            } ?: stringResource(R.string.chinese_setting_boshiamy_table_missing)
        }
    )

    if(table != null && !importing) {
        NavigationItem(
            title = stringResource(R.string.chinese_setting_boshiamy_table_remove),
            style = NavigationItemStyle.MiscNoArrow,
            navigate = {
                ChineseBoshiamy.removeTable(context)
                table = null
                GlobalIMEMessage.tryEmit(IMEMessage.ReloadResources)
            }
        )
    }
}
