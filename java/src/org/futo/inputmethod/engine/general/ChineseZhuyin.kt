package org.futo.inputmethod.engine.general

import java.io.File

/**
 * Zhuyin (Bopomofo) input for [ChineseIME], used by layouts with imeHint "zhuyin".
 *
 * The layout types Bopomofo symbols, but RIME's speller only accepts printable ASCII, so each
 * symbol is mapped to a private ASCII key before being passed to RIME. Letters are used instead of
 * the Dachen keys (1qaz2wsx...) so that digits and punctuation typed from the symbols layout keep
 * behaving as they do for Pinyin, and so that preedit editing (which only accepts letters) works.
 *
 * The schema is generated into the user directory and reuses the luna_pinyin dictionary that
 * already ships in the Chinese dictionary, converting its pinyin spellings to Zhuyin. luna_pinyin
 * has no tone information, so tones are optional and only act as syllable separators.
 *
 * As on desktop Zhuyin keyboards, space types the first tone after a syllable rather than
 * committing it.
 */
object ChineseZhuyin {
    const val SchemaId = "futo_zhuyin"

    private const val Symbols = "ㄅㄆㄇㄈㄉㄊㄋㄌㄍㄎㄏㄐㄑㄒㄓㄔㄕㄖㄗㄘㄙㄧㄨㄩㄚㄛㄜㄝㄞㄟㄠㄡㄢㄣㄤㄥㄦ"
    private const val Tones = "ˉˊˇˋ˙"

    // Same intermediate spelling as rime-bopomofo's zhuyin.yaml, one letter per symbol
    private const val SymbolKeys = "bpmfdtnlgkhjqxZCSrzcsiuvaoeEAIOUMNKGR"
    private const val InitialKeys = "bpmfdtnlgkhjqxZCSrzcs"

    // Tones 1-4, and Q for the neutral tone (qingsheng)
    private const val ToneKeys = "VWXYQ"
    private const val FirstToneKey = 'V'

    // Space is also a first tone. RIME's speller only takes it after a symbol, and otherwise
    // leaves it to commit the composition or type a space
    private const val FinalKeys = "$ToneKeys "

    /** RIME key -> Bopomofo symbol */
    val Transformation: Map<Char, Char> = (SymbolKeys + ToneKeys).zip(Symbols + Tones).toMap()

    private val toRime: Map<Int, Int> = Transformation.entries.associate { it.value.code to it.key.code }
    private val fromRime: Map<Int, Int> = Transformation.entries.associate { it.key.code to it.value.code }

    // Latin letters (e.g. from long-press) would be read as zhuyin keys, so they are sent as
    // X11 Unicode keysyms instead, which RIME passes through to be typed as-is
    private const val UnicodeKeysymOffset = 0x1000000

    fun toRimeKey(codePoint: Int): Int = toRime[codePoint] ?: when(codePoint) {
        in 'a'.code..'z'.code, in 'A'.code..'Z'.code -> UnicodeKeysymOffset + codePoint
        else -> codePoint
    }

    fun fromRimeKey(code: Int): Int = fromRime[code] ?: when {
        code > UnicodeKeysymOffset -> code - UnicodeKeysymOffset
        else -> code
    }

    /**
     * The key to record in the raw input for a space typed after [input], if it types the first
     * tone, which is the case after a symbol. Preedit editing only keeps letters, so it's recorded
     * as the first tone's letter
     */
    fun rawKeyForSpace(input: String): Char? =
        FirstToneKey.takeIf { input.lastOrNull()?.let { it in SymbolKeys } == true }

    // Spelling rules adapted from https://github.com/rime/rime-bopomofo (zhuyin.yaml)
    private val schema = """
        # Rime schema
        # encoding: utf-8
        #
        # Generated by FUTO Keyboard, any changes will be overwritten.

        schema:
          schema_id: $SchemaId
          name: 注音
          version: "1"
          description: |
            Zhuyin (Bopomofo) input based on the Luna Pinyin dictionary.

        switches:
          - name: ascii_mode
            reset: 0
            states: [ 中文, 西文 ]
          - name: full_shape
            states: [ 半角, 全角 ]
          - name: simplification
            states: [ 漢字, 汉字 ]
          - name: ascii_punct
            states: [ 。，, ．， ]

        engine:
          processors:
            - ascii_composer
            - key_binder
            - speller
            - punctuator
            - selector
            - navigator
            - express_editor
          segmentors:
            - ascii_segmentor
            - matcher
            - abc_segmentor
            - punct_segmentor
            - fallback_segmentor
          translators:
            - punct_translator
            - script_translator
          filters:
            - simplifier
            - simplifier@futo_zh_tw
            - uniquifier

        speller:
          alphabet: "$SymbolKeys$FinalKeys"
          initials: $SymbolKeys
          finals: "$FinalKeys"
          # Not space, which types the first tone
          delimiter: "'"
          use_space: true
          algebra:
            - xform/iu/iou/
            - xform/ui/uei/
            - xform/ong/ung/
            - xform/^yi?/i/
            - xform/^wu?/u/
            - xform/iu/v/
            - xform/^([jqx])u/$1v/
            - xform/([iuv])n/$1en/
            - xform/^zhi?/Z/
            - xform/^chi?/C/
            - xform/^shi?/S/
            - xform/^([zcsr])i/$1/
            - xform/ai/A/
            - xform/ei/I/
            - xform/ao/O/
            - xform/ou/U/
            - xform/ang/K/
            - xform/eng/G/
            - xform/an/M/
            - xform/en/N/
            - xform/er/R/
            - xform/eh/E/
            - xform/([iv])e/$1E/
            - abbrev/^([$InitialKeys]).+$/$1/
        ${FinalKeys.map { "    - \"derive/^([^$FinalKeys]+)$/$1$it/\"" }.joinToString("\n        ")}

        translator:
          dictionary: luna_pinyin
          prism: $SchemaId
          preedit_format:
            - "xlit|$SymbolKeys$FinalKeys|$Symbols${Tones}ˉ|"
            - "xform/'//"

        # Taiwan glyph standard (e.g. 為 instead of 爲), enabled when not simplifying
        futo_zh_tw:
          opencc_config: t2tw.json
          option_name: futo_zh_tw

        punctuator:
          import_preset: symbols

        key_binder:
          import_preset: default

        editor:
          bindings:
            # Commit the typed Zhuyin, as the raw input is only meaningful to RIME
            Return: commit_script_text

        __patch:
          - $SchemaId.custom:/patch?
    """.trimIndent() + "\n"

    // Only listed schemas get deployed
    private val defaultCustomization = """
        patch:
            schema_list/+:
                - schema: $SchemaId
    """.trimIndent() + "\n"

    /** Writes the schema to RIME's user directory, only touching files whose content changed */
    fun writeSchemaFiles(userDir: File) {
        if(!userDir.isDirectory) return

        listOf(
            File(userDir, "$SchemaId.schema.yaml") to schema,
            File(userDir, "default.custom.yaml") to defaultCustomization
        ).forEach { (file, content) ->
            if(!file.exists() || file.readText() != content) {
                file.writeText(content)
            }
        }
    }
}
